"""Generate LaTeX tables for the paper from the repo configs (single source of truth).

    python scripts/export_paper_tables.py ../BRIDGE_LandClassification_paper/tables

Requires \\usepackage{adjustbox} in the paper. Writes:
    legend.tex     BRIDGE classes, level-1 group, IGBP parent and extended Noah-MP code
"""

from __future__ import annotations

import argparse
from pathlib import Path

from bridge_lc.legend import IGBP20, load_legend


def _tex(s: str) -> str:
    return s.replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


def legend_table() -> str:
    legend = load_legend()
    rows = []
    for c in legend.classes:
        ext = rf"\textbf{{{c.noahmp_ext}}}" if c.noahmp_ext > 20 else str(c.noahmp_ext)
        name = c.name.replace("_", " ").capitalize()
        igbp = f"{c.igbp} ({_tex(IGBP20[c.igbp])})"
        rows.append(f"{c.id} & {_tex(name)} & {_tex(c.level1)} & {igbp} & {ext} \\\\")
    body = "\n".join(rows)
    return rf"""% AUTO-GENERATED by LandClassification_BRIDGE/scripts/export_paper_tables.py — do not edit.
% Legend {legend.name} v{legend.version}
\begin{{table*}}[t]
\centering
\caption{{BRIDGE Andes--Amazon legend (v{legend.version}) and its crosswalk to Noah-MP vegetation categories.
Standard: modified MODIS-IGBP 20-category scheme. Extended: proposed new Andean categories (bold, $>20$).}}
\label{{tab:legend}}
\begin{{adjustbox}}{{max width=\textwidth}}
\begin{{tabular}}{{r l l l c}}
\toprule
ID & Class & Group & Noah-MP standard (IGBP) & Extended \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{adjustbox}}
\end{{table*}}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir", type=Path)
    args = ap.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "legend.tex").write_text(legend_table())
    print(f"wrote {args.out_dir / 'legend.tex'}")


if __name__ == "__main__":
    main()
